/*
 * SpinSpec v1.1: Gnuplot rendering of invariant group strengths.
 * Input: Sp_invariant_<frame>.csv produced by experimental observer.
 * Outputs: group_curve_<frame>.dat, group_spectrum_<frame>.jpg.
 * Invariant DC is preserved. Display comprises a compact symbolic overview,
 * and exactly one local panel per displayed Graph spin (if Res files exist).
 * Each panel overlays its group, a thin Total curve and a thin signed
 * Interference curve on the same offset-frequency axis.
 * The original calculation and CSV fields are never changed.
 * All spectra are relative transition strengths, NOT FID amplitudes.
 *
 * Usage: ./group_graph 0 0.2 [spectrum_half_width_hz]
 */
#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <errno.h>

#define MAX_GROUPS 10
#define MAX_POINTS 2400
#define LOCAL_POINTS 2401
#define MAX_SPINS 128
#define MAX_LINE 2048
typedef struct {
    double frequency, total, cross;
    double group[MAX_GROUPS];
} Line;

static double lorentzian(double x,double f,double gamma) {
    double z=(x-f)/gamma;
    return 1.0/(1.0+z*z);
}

/* The web app passes group membership through the engine environment. */
static int read_membership(int ids[MAX_SPINS]) {
    const char *s=getenv("SPINSPEC_OBSERVER_GROUPS");
    if(!s||!*s)return 0;
    int count=0;
    while(*s){
        if(count>=MAX_SPINS)return -1;
        char *end=NULL;
        long group=strtol(s,&end,10);
        if(end==s||group<0||group>=MAX_GROUPS)return -1;
        ids[count++]=(int)group;
        if(*end=='\0')break;
        if(*end!=',')return -1;
        s=end+1;
        if(!*s)return -1;
    }
    return count;
}

/* Spin-indexed Y maxima delivered by engine_matrix from Graph heights.
 * A missing entry or a value <=0 means automatic scaling, as in GnuGraph.
 * The environment variable is optional for standalone group_graph usage. */
static int read_graph_heights(double heights[MAX_SPINS]) {
    const char *s = getenv("SPINSPEC_GRAPH_HEIGHTS");
    if (!s || !*s) return 0;
    int seen[MAX_SPINS] = {0};
    while (*s) {
        char *end = NULL;
        long spin = strtol(s, &end, 10);
        if (end == s || spin < 0 || spin >= MAX_SPINS ||
            *end != ':' || seen[spin]) return -1;
        s = end + 1;
        double limit = strtod(s, &end);
        if (end == s || !isfinite(limit)) return -1;
        heights[spin] = limit;
        seen[spin] = 1;
        if (*end == '\0') break;
        if (*end != ',') return -1;
        s = end + 1;
        if (!*s) return -1;
    }
    return 0;
}

typedef struct {
    int representative_spin;
    double center;
    double half_width;
    int occupied;
} GroupWindow;

/*
 * For a Graph spectrum half-width of zero, invariant transition strengths
 * determine a tighter window for each observed group and spin reference.
 * A positive Graph spectrum half-width is always respected exactly.
 * The original Sp, Res and invariant CSV files are not modified.
 */
static double auto_group_half_width(const Line *lines, size_t count,
                                    int group, double center,
                                    double allowed, double fwhm) {
     if (!lines || group < 0 || group >= MAX_GROUPS ||
        !isfinite(center) || !isfinite(allowed) || allowed <= 0 ||
        !isfinite(fwhm) || fwhm <= 0)
        return allowed;

    /* Exclude exact DC from the threshold used for finite transitions. */
    double peak = 0.0;
    for (size_t i = 0; i < count; ++i) {
        const double delta = fabs(lines[i].frequency - center);
        if (lines[i].frequency > 1e-9 && delta <= allowed &&
            lines[i].group[group] > peak)
            peak = lines[i].group[group];
    }
    if (peak <= 0.0)
        return allowed;

    /* Display-only cutoff: retain weak lines down to 1e-8 of the peak. */
    const double cutoff = fmax(1e-15, peak * 1e-8);
    double outermost = 0.0;
    int found = 0;
    for (size_t i = 0; i < count; ++i) {
        const double delta = fabs(lines[i].frequency - center);
        if (lines[i].frequency > 1e-9 && delta <= allowed &&
            lines[i].group[group] >= cutoff) {
            if (delta > outermost)
                outermost = delta;
            found = 1;
        }
    }
    if (!found)
        return allowed;

    const double margin = fmax(4.0 * fwhm, 0.12 * outermost);
    const double minimum = fmax(5.0, 10.0 * fwhm);
    return fmin(allowed, fmax(minimum, outermost + margin));
}

/* Res files are generated by the unchanged engine and give both the local
 * frequency origin and displayed half-width for each selected nucleus. */
static void locate_reference(long frame,int group,int nspins,
                             const int ids[MAX_SPINS],GroupWindow *window) {
    if(nspins<=0)return;
    for(int spin=0;spin<nspins;spin++) {
        if(ids[spin]!=group)continue;
        char path[128];
        snprintf(path,sizeof(path),"Res_%d_%05ld.dat",spin,frame);
        FILE *fp=fopen(path,"r");
        if(!fp)continue;  /* Some spin groups may have no displayed spin. */
        double shift=0,center=0,offset=0,intensity=0;
        int good=(fscanf(fp,"%lf %lf",&shift,&center)==2);
        double max_offset=0;
        int points=0;
        while (good && fscanf(fp,"%lf %lf",&offset,&intensity)==2) {
            if (!isfinite(offset)) { good=0; break; }
            max_offset=fmax(max_offset,fabs(offset));
            points++;
        }
        fclose(fp);
        if(good&&points>0&&isfinite(center)&&center>=0&&
           max_offset>0){
            window->center=center;
            window->half_width=max_offset;
            window->representative_spin=spin;
            return;
        }
    }
}

int main(int argc,char **argv) {
    if(argc<2||argc>4) {
        fprintf(stderr,"usage: %s FRAME [FWHM_HZ] [SPECTRUM_HALF_WIDTH_HZ]\n",argv[0]);
        return 2;
    }
    char *end=NULL;
    long frame=strtol(argv[1],&end,10);
    if(!end||*end||frame<0||frame>99999)return 2;
    double fwhm=argc>2?strtod(argv[2],&end):0.2;
    if(argc>2&&(!end||*end))return 2;
    if(!isfinite(fwhm)||fwhm<=0) {
        fprintf(stderr,"FWHM must be positive\n");
        return 2;
    }
    /* 0 enables automatic per-group zoom, positive preserves manual width.
     * Missing third argument retains the legacy manual-window behavior. */
    double requested_width = argc > 3 ? strtod(argv[3], &end) : 1.0;
    if ((argc > 3 && (!end || *end)) ||
        !isfinite(requested_width) || requested_width < 0.0) {
        fprintf(stderr, "Spectrum half-width must be nonnegative\n");
        return 2;
    }
    const int auto_x = (requested_width == 0.0);
    double left_override = NAN, right_override = NAN;
    const char *left_text = getenv("SPINSPEC_X_LEFT");
    const char *right_text = getenv("SPINSPEC_X_RIGHT");
    if (left_text && *left_text && strcmp(left_text, "auto") != 0) {
        char *tail = NULL;
        left_override = strtod(left_text, &tail);
        if (tail == left_text || *tail || !isfinite(left_override)) return 2;
    }
    if (right_text && *right_text && strcmp(right_text, "auto") != 0) {
        char *tail = NULL;
        right_override = strtod(right_text, &tail);
        if (tail == right_text || *tail || !isfinite(right_override)) return 2;
    }
    if (isfinite(left_override) && isfinite(right_override) &&
        left_override >= right_override) return 2;

    char in[128],out[128],curve[128];
    snprintf(in,sizeof(in),"Sp_invariant_%05ld.csv",frame);
    snprintf(out,sizeof(out),"group_spectrum_%05ld.jpg",frame);
    snprintf(curve,sizeof(curve),"group_curve_%05ld.dat",frame);
    FILE *fp=fopen(in,"r");
    if(!fp){perror(in);return 1;}
    char header[MAX_LINE];
    if(!fgets(header,sizeof(header),fp)){fclose(fp);return 1;}
    int groups=0;
    for(char *p=header;(p=strstr(p,"strength_g"))!=NULL;p+=10)groups++;
    if(groups<1||groups>MAX_GROUPS){
        fprintf(stderr,"Invalid number of group columns: %d\n",groups);
        fclose(fp);return 1;
    }
    size_t count=0,capacity=256;
    Line *lines=malloc(capacity*sizeof(*lines));
    if(!lines){fclose(fp);return 1;}
    double max_frequency=0,max_strength=0;
    char text[MAX_LINE];
    while(fgets(text,sizeof(text),fp)) {
        /* Strictly parse the nine fixed columns and all group strengths. */
        double dummy[9+MAX_GROUPS];
        int fields=0;
        char *save=NULL;
        for(char *tok=strtok_r(text,",\r\n",&save);tok;tok=strtok_r(NULL,",\r\n",&save)) {
            if(fields>=9+groups){fields=-999;break;}
            char *tail=NULL;
            dummy[fields]=strtod(tok,&tail);
            if(tail==tok||*tail||!isfinite(dummy[fields])){fields=-999;break;}
            fields++;
        }
        if(fields!=9+groups) {
            fprintf(stderr,"Invalid CSV row in %s\n",in);
            free(lines);fclose(fp);return 1;
        }
        double f=dummy[6],amp=dummy[7];
        if(f<0||amp< -1e-8){free(lines);fclose(fp);return 1;}
        if(count==capacity) {
            capacity*=2;
            Line *temp=realloc(lines,capacity*sizeof(*lines));
            if(!temp){free(lines);fclose(fp);return 1;}
            lines=temp;
        }
        Line *l=&lines[count++];
        memset(l,0,sizeof(*l));
        l->frequency=f;
        l->total=amp;
        l->cross=dummy[8];
        for(int g=0;g<groups;g++)l->group[g]=dummy[9+g];
        if(f>max_frequency)max_frequency=f;
        if(f>1e-9 && amp>max_strength)max_strength=amp;
    }
    fclose(fp);

    /* Display all significantly intense AC transitions; trivial zero-strength
       transitions at large Larmor-related gaps must not enlarge the graph. */
    double max_visible=0,min_visible=HUGE_VAL;
    double cutoff=fmax(1e-12,max_strength*1e-7);
    for(size_t i=0;i<count;i++) {
        if(lines[i].frequency>1e-9 && lines[i].total>cutoff) {
            if(lines[i].frequency>max_visible)max_visible=lines[i].frequency;
            if(lines[i].frequency<min_visible)min_visible=lines[i].frequency;
        }
    }
    if(max_visible<=0) {
        max_visible=fmax(30.,max_frequency);
        min_visible=0;
    }
    /* Include 0 Hz on the frequency axis for zero-field J spectra. */
    double xmax=max_visible*1.06+fmax(2.,2*fwhm);
    double xmin=0.;
    if(xmax>3000.&&min_visible>100.) {
        xmin=fmax(0.,min_visible-(max_visible-min_visible)*.06-2*fwhm);
    }
    if(xmax<=xmin)xmax=xmin+fmax(20.,fwhm*100);
    FILE *data=fopen(curve,"w");
    if(!data){perror(curve);free(lines);return 1;}
    /* Single data table: freq, total, groups, signed interference. */
    for(int k=0;k<MAX_POINTS;k++) {
        double x=xmin+(xmax-xmin)*k/(MAX_POINTS-1.0);
        double total=0,cross=0,gvals[MAX_GROUPS]={0};
        for(size_t i=0;i<count;i++) {
            const Line *l=&lines[i];
            if(l->frequency<xmin-40*fwhm||l->frequency>xmax+40*fwhm)continue;
            double w=lorentzian(x,l->frequency,fwhm/2);
            total+=w*l->total;cross+=w*l->cross;
            for(int g=0;g<groups;g++)gvals[g]+=w*l->group[g];
        }
        fprintf(data,"%.12g %.12g",x,total);
        for(int g=0;g<groups;g++)fprintf(data," %.12g",gvals[g]);
        fprintf(data," %.12g\n",cross);
    }
    fclose(data);
    double heights[MAX_SPINS]={0};
    if (read_graph_heights(heights)!=0) {
        fprintf(stderr,"Malformed SPINSPEC_GRAPH_HEIGHTS environment\n");
        free(lines);return 1;
    }
    int member_ids[MAX_SPINS]={0};
    int nspins=read_membership(member_ids);
    if(nspins<0){
        fprintf(stderr,"Malformed SPINSPEC_OBSERVER_GROUPS environment\n");
        free(lines);return 1;
    }
    GroupWindow windows[MAX_GROUPS]={0};
    int plotted_groups=0;
    for(int g=0;g<groups;g++){
        windows[g].representative_spin=-1;
        windows[g].half_width=25.; /* fallback for standalone CSV plotting */
        double largest=0.;
        for(size_t i=0;i<count;i++) {
            if(lines[i].group[g]>largest){
                largest=lines[i].group[g];
                windows[g].center=lines[i].frequency;
            }
        }
        if(largest<=1e-14)continue;
        windows[g].occupied=1;
        locate_reference(frame,g,nspins,member_ids,&windows[g]);
        if (auto_x)
            windows[g].half_width = auto_group_half_width(
                lines, count, g, windows[g].center,
                windows[g].half_width, fwhm);
        if (isfinite(left_override))
            windows[g].half_width = fmax(windows[g].half_width,
                                        fabs(left_override));
        if (isfinite(right_override))
            windows[g].half_width = fmax(windows[g].half_width,
                                        fabs(right_override));
        plotted_groups++;
    }
    if(plotted_groups<1){
        fprintf(stderr,"No group signals to render\n");
        free(lines);return 1;
    }

    /* Preserve the legacy global data file; broad high-field curves are not
     * sampled from it, because its frequency spacing can miss narrow lines. */
    char locals[MAX_GROUPS][128], components[MAX_GROUPS][128];
    for(int g=0;g<groups;g++){
        if(!windows[g].occupied)continue;
        snprintf(locals[g],sizeof(locals[g]),"group_local_g%d_%05ld.dat",g,frame);
        snprintf(components[g],sizeof(components[g]),
                 "group_local_components_g%d_%05ld.dat",g,frame);
        FILE *local=fopen(locals[g],"w");
        if(!local){perror(locals[g]);free(lines);return 1;}
        FILE *parts=fopen(components[g],"w");
        if(!parts){perror(components[g]);fclose(local);free(lines);return 1;}
        const double center=windows[g].center;
        const double width=windows[g].half_width;
        for(int k=0;k<LOCAL_POINTS;k++){
            double off=width*(2.*k/(LOCAL_POINTS-1.)-1.);
            double absolute=center+off;
            double strength=0.,total=0.,interference=0.;
            for(size_t i=0;i<count;i++){
                if(fabs(lines[i].frequency-center)>width+40.*fwhm)continue;
                double w=lorentzian(absolute,lines[i].frequency,fwhm/2.);
                strength+=lines[i].group[g]*w;
                total+=lines[i].total*w;
                interference+=lines[i].cross*w;
            }
            fprintf(local,"%.17g %.17g\n",off,strength);
            fprintf(parts,"%.17g %.17g %.17g\n",off,total,interference);
        }
        if(fclose(local)!=0){perror(locals[g]);fclose(parts);free(lines);return 1;}
        if(fclose(parts)!=0){perror(components[g]);free(lines);return 1;}
    }

    /* One graph panel per displayed spin, not per group.  The engine creates
     * Res_<spin> files only for the spins listed in the Graph record.  This
     * correctly handles two displayed spins belonging to the same group.
     * Retain the legacy per-group local data files unchanged. */
    typedef struct {
        int spin,group;
        double center,half_width;
        char local[128],parts[128];
    } DisplayPanel;
    DisplayPanel panels[MAX_SPINS];
    int panel_count=0;
    for(int spin=0;spin<nspins;spin++){
        int g=member_ids[spin];
        if(g<0||g>=groups){
            fprintf(stderr,"Membership group %d is absent from invariant CSV\n",g);
            free(lines);return 1;
        }
        char path[128];
        snprintf(path,sizeof(path),"Res_%d_%05ld.dat",spin,frame);
        FILE *rf=fopen(path,"r");
        if(!rf)continue;  /* The spin was not selected in Graph. */
        double shift=0,center=0,offset=0,intensity=0;
        int good=(fscanf(rf,"%lf %lf",&shift,&center)==2);
        double max_offset=0;
        int samples=0;
        while (good && fscanf(rf,"%lf %lf",&offset,&intensity)==2) {
            if (!isfinite(offset)) { good=0; break; }
            max_offset=fmax(max_offset,fabs(offset));
            samples++;
        }
        fclose(rf);
        if(!good||samples<1||!isfinite(center)||center<0||
           max_offset<=0){
            fprintf(stderr,"Invalid local frequency reference: %s\n",path);
            free(lines);return 1;
        }
        DisplayPanel *p=&panels[panel_count++];
        p->spin=spin;p->group=g;p->center=center;
        p->half_width = auto_x
            ? auto_group_half_width(lines, count, g, center, max_offset, fwhm)
            : max_offset;
        if (isfinite(left_override))
            p->half_width = fmax(p->half_width, fabs(left_override));
        if (isfinite(right_override))
            p->half_width = fmax(p->half_width, fabs(right_override));
        fprintf(stderr,
                "GROUP X-RANGE group=%d spin=%d mode=%s requested=%.6g selected=%.6g Hz\n",
                g, spin, auto_x ? "auto" : "manual", max_offset, p->half_width);
        if(windows[g].occupied && windows[g].representative_spin==spin &&
           fabs(p->center-windows[g].center)<1e-7 &&
           fabs(p->half_width-windows[g].half_width)<1e-7){
            snprintf(p->local,sizeof(p->local),"%s",locals[g]);
            snprintf(p->parts,sizeof(p->parts),"%s",components[g]);
        }else{
            /* Second selected spin of a group has its own frequency window. */
            snprintf(p->local,sizeof(p->local),
                     "group_local_spin%d_%05ld.dat",spin,frame);
            snprintf(p->parts,sizeof(p->parts),
                     "group_components_spin%d_%05ld.dat",spin,frame);
            FILE *lf=fopen(p->local,"w");
            if(!lf){perror(p->local);free(lines);return 1;}
            FILE *pf=fopen(p->parts,"w");
            if(!pf){perror(p->parts);fclose(lf);free(lines);return 1;}
            for(int k=0;k<LOCAL_POINTS;k++){
                double off=p->half_width*(2.*k/(LOCAL_POINTS-1.)-1.);
                double absf=p->center+off;
                double group_strength=0,total=0,cross=0;
                for(size_t i=0;i<count;i++){
                    if(fabs(lines[i].frequency-p->center)>
                       p->half_width+40.*fwhm)continue;
                    double w=lorentzian(absf,lines[i].frequency,fwhm/2.);
                    group_strength+=w*lines[i].group[g];
                    total+=w*lines[i].total;
                    cross+=w*lines[i].cross;
                }
                fprintf(lf,"%.17g %.17g\n",off,group_strength);
                fprintf(pf,"%.17g %.17g %.17g\n",off,total,cross);
            }
            int close_local=fclose(lf);
            int close_parts=fclose(pf);
            if(close_local!=0||close_parts!=0){
                fprintf(stderr,"Unable to write spin-local curves\n");
                free(lines);return 1;
            }
        }
    }
    /* For standalone CSV plotting without Res files, preserve one panel per
     * occupied group so that a useful graph can still be produced. */
    if(panel_count==0){
        for(int g=0;g<groups;g++){
            if(!windows[g].occupied)continue;
            DisplayPanel *p=&panels[panel_count++];
            p->spin=windows[g].representative_spin;
            p->group=g;
            p->center=windows[g].center;
            p->half_width=windows[g].half_width;
            snprintf(p->local,sizeof(p->local),"%s",locals[g]);
            snprintf(p->parts,sizeof(p->parts),"%s",components[g]);
        }
    }
    if(panel_count==0){
        fprintf(stderr,"No displayed spin groups to render\n");
        free(lines);return 1;
    }

    /* Absolute-frequency stick overview includes mathematically defined DC.
     * The local panels are centered independently on each group's resonance. */
    char overview[128];
    snprintf(overview,sizeof(overview),"group_sticks_%05ld.dat",frame);
    FILE *st=fopen(overview,"w");
    if(!st){perror(overview);free(lines);return 1;}
    for(size_t i=0;i<count;i++){
        fprintf(st,"%.17g %.17g\n",lines[i].frequency,lines[i].total);
    }
    if(fclose(st)!=0){perror(overview);free(lines);return 1;}

    char script[128];
    snprintf(script,sizeof(script),"group_plot_%05ld.gp",frame);
    FILE *gp=fopen(script,"w");
    if(!gp){perror(script);free(lines);return 1;}
    /* The overview is schematic.  All lower panels are keyed to the Graph
     * list and each overlays group strength (thick), Total and signed
     * Interference (thin).  No separate Total or Interference panel. */
    fprintf(gp,"set terminal jpeg size 1800,%d enhanced font 'Sans,15'\n",
            360*panel_count+150);
    fprintf(gp,"set output '%s'\n",out);
    fprintf(gp,"set multiplot title 'SpinSpec: group-resolved spectra (invariant DC included)' font 'Sans,20'\n");
    fprintf(gp,"set grid xtics ytics\nset zeroaxis\nset key off\n");
    fprintf(gp,"set origin 0,0.86\nset size 1,0.12\n");
    fprintf(gp,"unset ytics\nset border 1\nunset grid\n");
    fprintf(gp,"set lmargin 10\nset rmargin 4\n");
    fprintf(gp,"set title 'Transition positions (schematic)'\n");
    fprintf(gp,"set xlabel 'Absolute frequency (Hz)'\n");
    fprintf(gp,"unset ylabel\n");
    double left=(xmin==0.0)?-fmax(1.,4.*fwhm):xmin;
    fprintf(gp,"set xrange [%.17g:%.17g]\n",left,xmax);
    fprintf(gp,"set yrange [0:1]\n");
    fprintf(gp,"plot '%s' using 1:($2>%.17g ? 0.28 : 1/0) with impulses lw 2 lc rgb '#444444'\n",
            overview,cutoff);
    fprintf(gp,"set ytics autofreq\nset border 15\nset grid xtics ytics\n");

    const double row_height=0.83/panel_count;
    const char *colors[MAX_GROUPS]={"#16833a","#146aff","#af24c6",
        "#d46900","#009a9a","#994100","#a42040","#668800","#5555aa","#333333"};
    for(int j=0;j<panel_count;j++){
        const DisplayPanel *p=&panels[j];
        int g=p->group;
        fprintf(gp,"set origin 0,%.12g\nset size 1,%.12g\n",
                (panel_count-1-j)*row_height,row_height);
        fprintf(gp,"set lmargin 10\nset rmargin 4\n");
        if(p->spin>=0){
            fprintf(gp,"set title 'Group %d (spin %d), reference %.8g Hz'\n",
                    g,p->spin,p->center);
        }else{
            fprintf(gp,"set title 'Group %d, window near %.8g Hz'\n",
                    g,p->center);
        }
        fprintf(gp,"set xlabel 'Frequency offset (Hz)'\n");
        fprintf(gp,"set ylabel 'Relative strength'\n");
        double panel_left = -p->half_width;
        double panel_right = p->half_width;
        if (auto_x) panel_left = fmax(panel_left, -p->center);
        if (isfinite(left_override)) panel_left = left_override;
        if (isfinite(right_override)) panel_right = right_override;
        if (!(panel_left < panel_right)) {
            fprintf(stderr, "Invalid group panel XRange (%g:%g)\n",
                    panel_left, panel_right);
            fclose(gp);free(lines);return 1;
        }
        fprintf(gp,"set xrange [%.17g:%.17g]\n",
                panel_left,panel_right);
        /* Graph heights limits the positive Y maximum.  The negative end
         * stays automatic so signed Interference is never silently hidden.
         * Height 0 preserves the current automatic scale. */
        if (p->spin>=0 && p->spin<MAX_SPINS && heights[p->spin]>0.0)
            fprintf(gp,"set yrange [*:%.17g]\n",heights[p->spin]);
        else
            fprintf(gp,"set yrange [*:*]\n");
        fprintf(gp,"set key inside top right horizontal\n");
        fprintf(gp,"plot '%s' using 1:2 with lines lw 2.2 lc rgb '%s' title 'Group %d',",
                p->local,colors[g],g);
        fprintf(gp," '%s' using 1:2 with lines lw 0.9 lc rgb '#565656' title 'Total',",
                p->parts);
        fprintf(gp," '%s' using 1:3 with lines lw 0.9 lc rgb '#00a3b6' title 'Interference'\n",
                p->parts);
    }
    fprintf(gp,"unset multiplot\nunset output\n");
    if(fclose(gp)!=0){perror(script);free(lines);return 1;}
    char command[256];
    snprintf(command,sizeof(command),"gnuplot < %s",script);
    int status=system(command);
    free(lines);
    if(status!=0){
        fprintf(stderr,"Gnuplot failed (status=%d; script=%s)\n",status,script);
        return 1;
    }
    printf("SpinSpec: schematic + %d displayed-spin panels (group + Total + signed interference) written to %s (DC retained)\n",
           panel_count,out);
    return 0;
}
